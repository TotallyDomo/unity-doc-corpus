package main

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const corpusMarker = ".unity-doc-agent-corpus"
const completeMarker = "generated by unity-doc-corpus\ncomplete\n"
const stagingMarker = "generated by unity-doc-corpus\nstaging\n"

func resolveBuildPath(path string) (string, error) {
	resolved, err := filepath.EvalSymlinks(path)
	if err == nil {
		return resolved, nil
	}
	if !os.IsNotExist(err) || filepath.Dir(path) == path {
		return "", err
	}
	parent, err := resolveBuildPath(filepath.Dir(path))
	return filepath.Join(parent, filepath.Base(path)), err
}

func validateBuildPaths(source, output string) error {
	source, err := resolveBuildPath(source)
	if err != nil {
		return err
	}
	output, err = resolveBuildPath(output)
	if err != nil {
		return err
	}
	within := func(parent, child string) bool {
		rel, err := filepath.Rel(parent, child)
		return err == nil && rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))
	}
	for _, candidate := range []string{output, output + ".staging", output + ".previous"} {
		if within(candidate, source) {
			return fmt.Errorf("output publication path contains source: %s", candidate)
		}
		for _, section := range sectionDirs {
			if within(filepath.Join(source, section), candidate) {
				return fmt.Errorf("output publication path is inside a source section: %s", candidate)
			}
		}
	}
	return nil
}

// outputPublication owns one sibling stage and backup while holding the output's
// process-scoped writer lock. Recovery and publication never merge directories.
type outputPublication struct {
	output, stage, previous string
	lock                    *os.File
	rename                  func(string, string) error
}

func (p *outputPublication) markerMatches(data []byte, prefix string) bool {
	if !strings.HasPrefix(string(data), prefix) {
		return false
	}
	owner := strings.TrimSuffix(strings.TrimPrefix(string(data), prefix), "\n")
	rel, err := filepath.Rel(p.output, owner)
	return err == nil && rel == "."
}

func markedOutput(path string) (bool, error) {
	info, err := os.Lstat(path)
	if os.IsNotExist(err) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return false, fmt.Errorf("refusing non-directory or linked output: %s", path)
	}
	marker, err := os.Lstat(filepath.Join(path, corpusMarker))
	if err != nil || !marker.Mode().IsRegular() {
		return false, fmt.Errorf("refusing to overwrite unmarked output directory: %s", path)
	}
	return true, nil
}

func beginPublication(output string) (*outputPublication, error) {
	if err := os.MkdirAll(filepath.Dir(output), 0755); err != nil {
		return nil, err
	}
	parent, err := filepath.EvalSymlinks(filepath.Dir(output))
	if err != nil {
		return nil, err
	}
	output = filepath.Join(parent, filepath.Base(output))
	lock, err := lockOutput(output + ".build.lock")
	if err != nil {
		return nil, fmt.Errorf("locking corpus output %s: %w", output, err)
	}
	p := &outputPublication{output: output, stage: output + ".staging", previous: output + ".previous", lock: lock, rename: os.Rename}
	if err := p.recover(); err != nil {
		lock.Close()
		return nil, err
	}
	if err := os.Mkdir(p.stage, 0755); err != nil {
		lock.Close()
		return nil, err
	}
	if err := os.WriteFile(filepath.Join(p.stage, corpusMarker), []byte(stagingMarker+p.output+"\n"), 0644); err != nil {
		// WHY: Only this just-created directory is known to be ours without a marker.
		cleanupErr := os.RemoveAll(p.stage)
		lock.Close()
		return nil, errors.Join(err, cleanupErr)
	}
	return p, nil
}

// recover restores the last good path after a parked-old interruption, or keeps
// the completed new generation after installation. Unknown directories refuse.
func (p *outputPublication) recover() error {
	out, err := markedOutput(p.output)
	if err != nil {
		return err
	}
	old, err := markedOutput(p.previous)
	if err != nil {
		return err
	}
	stage, err := markedOutput(p.stage)
	if err != nil {
		return err
	}
	if stage {
		marker, err := os.ReadFile(filepath.Join(p.stage, corpusMarker))
		if err != nil || (!p.markerMatches(marker, stagingMarker) && !p.markerMatches(marker, completeMarker)) {
			return fmt.Errorf("refusing stage not owned by this output: %s", p.stage)
		}
	}
	if old {
		if !out {
			if err := p.rename(p.previous, p.output); err != nil {
				return fmt.Errorf("restore previous corpus from %s: %w", p.previous, err)
			}
		} else {
			marker, err := os.ReadFile(filepath.Join(p.output, corpusMarker))
			if err != nil || !p.markerMatches(marker, completeMarker) {
				return fmt.Errorf("ambiguous publication; preserve %s and %s for inspection", p.output, p.previous)
			}
			if err := os.RemoveAll(p.previous); err != nil {
				return fmt.Errorf("remove retired corpus %s: %w", p.previous, err)
			}
		}
	}
	if stage {
		if err := os.RemoveAll(p.stage); err != nil {
			return fmt.Errorf("remove abandoned stage %s: %w", p.stage, err)
		}
	}
	return nil
}

func (p *outputPublication) publish() error {
	if err := os.WriteFile(filepath.Join(p.stage, corpusMarker), []byte(completeMarker+p.output+"\n"), 0644); err != nil {
		return err
	}
	old, err := markedOutput(p.output)
	if err != nil {
		return err
	}
	if old {
		if err := p.rename(p.output, p.previous); err != nil {
			return fmt.Errorf("park previous corpus: %w", err)
		}
	}
	if err := p.rename(p.stage, p.output); err != nil {
		if old {
			err = errors.Join(err, p.rename(p.previous, p.output))
		}
		return fmt.Errorf("publish corpus (retry build to recover; previous is %s): %w", p.previous, err)
	}
	if old {
		if err := os.RemoveAll(p.previous); err != nil {
			return fmt.Errorf("new corpus installed; retired corpus cleanup failed (retry build): %w", err)
		}
	}
	return nil
}

func (p *outputPublication) close() error {
	// WHY: On failed rollback the previous directory must survive for the next build.
	err := os.RemoveAll(p.stage)
	return errors.Join(err, p.lock.Close())
}
